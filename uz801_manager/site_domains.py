"""Opt-in publication of managed virtual hosts; DNS is never changed here."""
import os
from pathlib import Path
import re
import subprocess
import tempfile

from .static_site import SiteError


class DomainPublisher:
    INCLUDE = ' include /etc/nginx/openstick-panel.conf; # OpenStick web panel\n'
    BEGIN = '  # BEGIN OPENSTICK WEB PANEL\n'
    END = '  # END OPENSTICK WEB PANEL\n'

    def __init__(self, *, nginx='/etc/nginx/nginx.conf', virtual_hosts='/etc/nginx/openstick-panel.conf',
                 tunnel='/etc/cloudflared/config.yml', run=subprocess.run):
        self.nginx, self.virtual_hosts, self.tunnel = map(Path, (nginx, virtual_hosts, tunnel))
        self.run = run

    def available(self):
        return os.name != 'nt' and self.nginx.is_file() and self.tunnel.is_file()

    @staticmethod
    def atomic(path, data, metadata=None):
        fd, name = tempfile.mkstemp(prefix='.openstick-', dir=path.parent)
        try:
            with os.fdopen(fd, 'wb') as output:
                output.write(data);output.flush();os.fsync(output.fileno())
            os.chmod(name, metadata.st_mode & 0o777 if metadata else 0o644)
            if metadata and hasattr(os, 'chown'):os.chown(name, metadata.st_uid, metadata.st_gid)
            os.replace(name, path)
        finally:Path(name).unlink(missing_ok=True)

    def command(self, args):
        try:result = self.run(args, capture_output=True, timeout=35, check=False)
        except (OSError, subprocess.SubprocessError):raise SiteError('DOMAIN_SERVICE_FAILED') from None
        if result.returncode:raise SiteError('DOMAIN_SERVICE_FAILED')

    def plan(self, sites, primary):
        if not self.available():raise SiteError('DOMAIN_PUBLISH_UNAVAILABLE')
        paths = [self.nginx, self.virtual_hosts, self.tunnel]
        if any(p.is_symlink() for p in paths):raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
        original = {p: (p.read_bytes(), p.stat()) if p.exists() else (None, None) for p in paths}
        nginx = original[self.nginx][0].decode('utf-8').replace('\r\n', '\n')
        if self.INCLUDE not in nginx:
            matches = list(re.finditer(r'^http[ \t]*\{[ \t]*$', nginx, re.M))
            if len(matches) != 1:raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
            point = matches[0].end()
            nginx = nginx[:point] + '\n' + self.INCLUDE + nginx[point:]
        tunnel = original[self.tunnel][0].decode('utf-8').replace('\r\n', '\n')
        if self.BEGIN in tunnel or self.END in tunnel:
            if tunnel.count(self.BEGIN) != 1 or tunnel.count(self.END) != 1:raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
            start, end = tunnel.index(self.BEGIN), tunnel.index(self.END)
            if start >= end:raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
            tunnel = tunnel[:start] + tunnel[end + len(self.END):]
        # Only the originally installed, simple local-managed ingress is supported.
        # Refuse unknown ingress/originRequest schemas instead of rewriting them.
        base = re.compile(r'(?P<prefix>[\s\S]*?^ingress:\n)'
                          r'  - hostname: ' + re.escape(primary) + r'\n'
                          r'    service: http://127\.0\.0\.1:8080\n'
                          r'(?P<tail>  - service: http_status:404\n?)\Z', re.M)
        match = base.fullmatch(tunnel)
        if not match:raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
        hosts, rules = [], []
        for site in sites:
            names = [d for d in site['domains'] if d != primary]
            if not names:continue
            root = str(site['root'])
            # Roots are generated by the registry, never accepted from an API.
            if not re.fullmatch(r'/[A-Za-z0-9_/-]+', root):raise SiteError('DOMAIN_CONFIG_UNSUPPORTED')
            hosts.append('server {\n listen 127.0.0.1:8080;\n server_name ' + ' '.join(names) + ';\n'
                         ' root ' + root + ';\n index index.html;\n autoindex off;\n'
                         ' location ~ /\\. { deny all; }\n'
                         ' location / { try_files $uri $uri/ =404; }\n}\n')
            rules += ['  - hostname: ' + domain + '\n    service: http://127.0.0.1:8080\n' for domain in names]
        marker = self.BEGIN + ''.join(rules) + self.END
        position = tunnel.rfind(match['tail'])
        tunnel = tunnel[:position] + marker + tunnel[position:]
        return original, {self.nginx: nginx.encode(), self.virtual_hosts: ''.join(hosts).encode(),
                          self.tunnel: tunnel.encode()}

    def state(self, sites, primary):
        if not self.available():return {'available': False, 'local': 'NOT_INSTALLED', 'dns': 'UNVERIFIED'}
        try:
            original, proposed = self.plan(sites, primary)
            applied = all(original[p][0] == data for p, data in proposed.items())
            return {'available': True, 'local': 'CONFIG_SAVED' if applied else 'PENDING', 'dns': 'UNVERIFIED'}
        except SiteError as error:return {'available': False, 'local': str(error), 'dns': 'UNVERIFIED'}

    def apply(self, sites, primary, private):
        original, proposed = self.plan(sites, primary)
        private = Path(private);private.mkdir(parents=True, exist_ok=True, mode=0o700)
        backup = Path(tempfile.mkdtemp(prefix='domains-', dir=private))
        for index, (data, metadata) in enumerate(original.values()):
            if data is not None:
                file = backup / str(index);file.write_bytes(data);os.chmod(file, 0o600)
        touched = []
        commands = [['/usr/sbin/nginx', '-t'],
                    ['/usr/local/bin/cloudflared', '--config', str(self.tunnel), 'tunnel', 'ingress', 'validate']]
        activated = False
        try:
            for path, data in proposed.items():
                self.atomic(path, data, original[path][1]);touched.append(path)
            for args in commands:self.command(args)
            activated = True
            self.command(['/usr/sbin/nginx', '-s', 'reload'])
            self.command(['rc-service', 'cloudflared', 'restart'])
        except Exception:
            try:
                for path in reversed(touched):
                    data, metadata = original[path]
                    if data is None:path.unlink(missing_ok=True)
                    else:self.atomic(path, data, metadata)
                if activated:
                    self.command(['/usr/sbin/nginx', '-s', 'reload'])
                    self.command(['rc-service', 'cloudflared', 'restart'])
            except Exception:raise SiteError('DOMAIN_ROLLBACK_FAILED') from None
            raise SiteError('DOMAIN_PUBLISH_FAILED') from None
        return {'local': 'CONFIG_SAVED', 'dns': 'UNVERIFIED', 'backup': backup.name}
